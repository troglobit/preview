#!/usr/bin/env python3
"""Generate static/css/themes.css from Primer's theme palettes.

Each GitHub theme is one block of CSS variables on :root.  The variables
are the ones github-markdown.css, syntax.css and the preview UI read.
Colorblind themes are written as overlays holding only what differs from
the base theme.  Dark dimmed has no colorblind palette in Primer, so it
gets dark's overlay.

Usage: gen-themes.py DIR VERSION > static/css/themes.css

DIR holds light.css, dark.css, dark-dimmed.css, light-colorblind.css and
dark-colorblind.css from @primer/primitives/dist/css/functional/themes/,
and VERSION is the package version they came from, for the header.
"""

import re
import sys
from pathlib import Path

VARIABLES = """
bgColor-attention-muted bgColor-danger-muted bgColor-default bgColor-emphasis
bgColor-muted bgColor-neutral-muted borderColor-accent-emphasis
borderColor-attention-emphasis borderColor-danger-emphasis borderColor-default
borderColor-done-emphasis borderColor-muted borderColor-neutral-muted
borderColor-success-emphasis fgColor-accent fgColor-attention fgColor-danger
fgColor-default fgColor-done fgColor-muted fgColor-onEmphasis fgColor-success
focus-outlineColor overlay-bgColor shadow-floating-medium
color-prettylights-syntax-brackethighlighter-angle
color-prettylights-syntax-brackethighlighter-unmatched
color-prettylights-syntax-carriage-return-bg
color-prettylights-syntax-carriage-return-text
color-prettylights-syntax-comment color-prettylights-syntax-constant
color-prettylights-syntax-constant-other-reference-link
color-prettylights-syntax-entity color-prettylights-syntax-entity-tag
color-prettylights-syntax-invalid-illegal-bg
color-prettylights-syntax-invalid-illegal-text
color-prettylights-syntax-keyword color-prettylights-syntax-markup-bold
color-prettylights-syntax-markup-changed-bg
color-prettylights-syntax-markup-changed-text
color-prettylights-syntax-markup-deleted-bg
color-prettylights-syntax-markup-deleted-text
color-prettylights-syntax-markup-heading
color-prettylights-syntax-markup-ignored-bg
color-prettylights-syntax-markup-ignored-text
color-prettylights-syntax-markup-inserted-bg
color-prettylights-syntax-markup-inserted-text
color-prettylights-syntax-markup-italic color-prettylights-syntax-markup-list
color-prettylights-syntax-meta-diff-range
color-prettylights-syntax-storage-modifier-import
color-prettylights-syntax-string color-prettylights-syntax-string-regexp
color-prettylights-syntax-sublimelinter-gutter-mark
color-prettylights-syntax-variable
""".split()


def palette(path):
    text = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
    found = {}
    for name, value in re.findall(r"--([A-Za-z0-9-]+)\s*:\s*([^;]+);", text):
        found.setdefault(name, value.strip())
    missing = [v for v in VARIABLES if v not in found]
    if missing:
        sys.exit(f"{path.name}: missing {' '.join(missing)}")

    # Primer aliases some values to other variables; inline them so the
    # output stands on its own.
    def resolve(value):
        return re.sub(r"var\(--([A-Za-z0-9-]+)\)", lambda m: resolve(found[m.group(1)]), value)

    return {v: resolve(found[v]) for v in VARIABLES}


def block(selector, values, indent=""):
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  {'' if k == 'color-scheme' else '--'}{k}: {v};" for k, v in values.items()]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def overlay(base, variant):
    return {k: v for k, v in variant.items() if base[k] != v}


def main():
    d, version = Path(sys.argv[1]), sys.argv[2]
    light = palette(d / "light.css")
    dark = palette(d / "dark.css")
    dimmed = palette(d / "dark-dimmed.css")
    light_cb = overlay(light, palette(d / "light-colorblind.css"))
    dark_cb = overlay(dark, palette(d / "dark-colorblind.css"))

    light["color-scheme"] = "light"
    dark["color-scheme"] = "dark"
    dimmed["color-scheme"] = "dark"

    out = [
        f"/* Generated by gen-themes.py from @primer/primitives {version}. Do not edit. */",
        "/* The theme is picked by data-theme on <html>, or the OS without it;",
        "   data-colorblind swaps in GitHub's colorblind hues. */",
        "",
        block(':root', light),
        "",
        "@media (prefers-color-scheme: dark) {",
        block(":root:not([data-theme])", dark, "  "),
        "}",
        "",
        block(':root[data-theme="dark"]', dark),
        "",
        block(':root[data-theme="dimmed"]', dimmed),
        "",
        block(':root[data-colorblind]', light_cb),
        "",
        "@media (prefers-color-scheme: dark) {",
        block(":root:not([data-theme])[data-colorblind]", dark_cb, "  "),
        "}",
        "",
        block(':root[data-theme="dark"][data-colorblind],\n:root[data-theme="dimmed"][data-colorblind]', dark_cb),
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
